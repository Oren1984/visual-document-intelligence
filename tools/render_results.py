"""Render results/metrics.json into results/summary.md and an errors-by-field chart (SVG) for the docs and the site.

    python tools/render_results.py

Numbers are read from the metrics file only; nothing is typed in by hand.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from vdi.schema import FIELDS, LABELS  # noqa: E402

M = json.loads((ROOT / "results" / "metrics.json").read_text(encoding="utf-8"))
P = M["paths"]
NAME = {"direct": "Direct (image)", "ocr": "OCR-assisted (text)"}
# Validated categorical pair on the dark surfaces (dataviz validator: CVD ΔE 26.8, normal 31.8, ≥3:1 contrast)
COLOR = {"direct": "#3987e5", "ocr": "#d95926"}
CONDITIONS = ["clean", "rotated", "blurred", "noisy_jpeg", "faded", "low_res"]


def pct(x: float) -> str:
    return f"{x * 100:.1f}%"


def summary_md() -> str:
    n = M["documents"]
    out = [f"# Evaluation summary (generated)\n",
           f"Generated by `tools/render_results.py` from `results/metrics.json` (run {M['created']}). "
           f"{n} documents × {len(FIELDS)} fields = {n * len(FIELDS)} field slots per path.\n",
           "## Headline\n",
           "| Path | Field accuracy | Exact-match documents | Key-value P / R / F1 | Failed runs | Median s/doc | Mean s/doc |",
           "|---|---:|---:|---:|---:|---:|---:|"]
    for k, p in P.items():
        kv = p["kv"]
        out.append(f"| {NAME[k]} | {p['correct']}/{p['field_slots']} = {pct(p['field_accuracy'])} | "
                   f"{p['exact_match_docs']}/{p['documents']} | {kv['precision']:.3f} / {kv['recall']:.3f} / {kv['f1']:.3f} | "
                   f"{p['failed_runs']} | {p['seconds']['median']} | {p['seconds']['mean']} |")
    s = P["ocr"]["seconds"]["stages_mean"]
    out.append(f"\nOCR-assisted mean stage times: OCR {s.get('ocr_s')} s + model {s.get('model_s')} s.\n")
    out += ["## Per field (correct / incorrect / missing / spurious, out of 30)\n",
            "| Field | Direct | OCR-assisted |", "|---|---|---|"]
    for f in FIELDS:
        cells = []
        for k in P:
            c = P[k]["per_field"][f]
            cells.append(f"{c['correct']} / {c['incorrect']} / {c['missing']} / {c['spurious']}")
        out.append(f"| {LABELS[f]} | {cells[0]} | {cells[1]} |")
    out += ["\n## Per image condition (correct field slots out of 30 = 5 receipts × 6 fields)\n",
            "| Condition | Direct | OCR-assisted |", "|---|---:|---:|"]
    for c in CONDITIONS:
        out.append(f"| {c.replace('_', ' ')} | {P['direct']['by_condition'][c]['correct']} | {P['ocr']['by_condition'][c]['correct']} |")
    out += ["\n## Would a reviewer be pointed to the errors?\n",
            "| Path | Errors | Flagged by a rule | Flagged only by path disagreement | Not flagged | Flags on correct fields |",
            "|---|---:|---:|---:|---:|---:|"]
    for k, p in P.items():
        r = p["review"]
        out.append(f"| {NAME[k]} | {r['errors']} | {r['flagged_rule']} | {r['flagged_disagree_only']} | {r['unflagged']} | {r['false_alarms']} |")
    out += ["\n## Every error\n", "| Path | Doc | Layout · condition | Field | Outcome | Truth | Predicted | Flag |", "|---|---|---|---|---|---|---|---|"]
    for k, p in P.items():
        for e in p["errors"]:
            flag = "rule" if e["flagged_rule"] else ("paths differ" if e["flagged_disagreement"] else "—")
            out.append(f"| {NAME[k]} | {e['id']} | {e['template']} · {e['condition'].replace('_', ' ')} | {LABELS[e['field']]} | "
                       f"{e['outcome']} | `{e['truth']}` | `{e['predicted']}` | {flag} |")
    env = M["environment"]
    out += ["\n## Environment\n", f"- Model: `{env['model']}` (digest `{(env.get('digest') or '')[:12]}…`), Ollama {env['ollama']}, "
            f"processor {env.get('processor')}, endpoint {env['endpoint']}", f"- Decoding: {env['decoding']}",
            f"- OCR: {env['ocr']}", f"- Python {env['python']} on {env['os']}; CPU {env['machine']}"]
    return "\n".join(out) + "\n"


def chart_svg() -> str:
    """Grouped horizontal bars: non-correct field outcomes per field, per path. Dark surface, direct labels, <title> tooltips."""
    W, left, right, top, row_h, bar_h, gap = 720, 150, 70, 64, 46, 14, 2
    H = top + row_h * len(FIELDS) + 44
    maxv = max(max(30 - P[k]["per_field"][f]["correct"] for f in FIELDS) for k in P)
    maxv = max(maxv, 4)
    scale = (W - left - right) / maxv
    t = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %d %d" role="img" aria-labelledby="t d" font-family="Inter, Segoe UI, system-ui, sans-serif">' % (W, H),
         '<title id="t">Errors per field, by extraction path</title>',
         '<desc id="d">Out of 30 receipts per field. ' + "; ".join(
             f"{LABELS[f]}: direct {30 - P['direct']['per_field'][f]['correct']}, OCR-assisted {30 - P['ocr']['per_field'][f]['correct']}" for f in FIELDS) + '</desc>',
         f'<rect width="{W}" height="{H}" rx="12" fill="#12233A"/>',
         '<text x="24" y="30" fill="#F8FAFC" font-size="15" font-weight="700">Errors per field (out of 30 receipts)</text>']
    lx = W - right - 250
    for i, k in enumerate(P):
        x = lx + i * 130
        t.append(f'<rect x="{x}" y="19" width="12" height="12" rx="2" fill="{COLOR[k]}"/>')
        t.append(f'<text x="{x + 18}" y="30" fill="#A9B8CC" font-size="12">{NAME[k]}</text>')
    for v in range(0, maxv + 1, 2 if maxv > 6 else 1):
        x = left + v * scale
        t.append(f'<line x1="{x:.1f}" y1="{top - 8}" x2="{x:.1f}" y2="{H - 34}" stroke="#243852" stroke-width="1"/>')
        t.append(f'<text x="{x:.1f}" y="{H - 16}" fill="#8A9BB3" font-size="11" text-anchor="middle">{v}</text>')
    for r, f in enumerate(FIELDS):
        y0 = top + r * row_h
        t.append(f'<text x="{left - 12}" y="{y0 + bar_h + 5}" fill="#A9B8CC" font-size="13" text-anchor="end">{LABELS[f]}</text>')
        for i, k in enumerate(P):
            c = P[k]["per_field"][f]
            v = 30 - c["correct"]
            y = y0 + i * (bar_h + gap)
            w = max(v * scale, 0)
            tip = f"{NAME[k]} · {LABELS[f]}: {v} errors ({c['incorrect']} incorrect, {c['missing']} missing, {c['spurious']} spurious)"
            if w > 0:
                t.append(f'<g><title>{tip}</title><path d="M{left},{y} h{w - 4:.1f} a4,4 0 0 1 4,4 v{bar_h - 8} a4,4 0 0 1 -4,4 h-{w - 4:.1f} z" fill="{COLOR[k]}"/>'
                         f'<rect x="{left}" y="{y - 1}" width="{W - left - right}" height="{bar_h + 2}" fill="transparent"/></g>')
            else:
                t.append(f'<g><title>{tip}</title><rect x="{left}" y="{y}" width="2" height="{bar_h}" fill="{COLOR[k]}"/></g>')
            t.append(f'<text x="{left + w + 6:.1f}" y="{y + bar_h - 3}" fill="#F8FAFC" font-size="11">{v}</text>')
    t.append(f'<line x1="{left}" y1="{top - 8}" x2="{left}" y2="{H - 34}" stroke="#74869E" stroke-width="1"/>')
    t.append("</svg>")
    return "\n".join(t) + "\n"


def main() -> int:
    (ROOT / "results" / "summary.md").write_text(summary_md(), encoding="utf-8")
    svg = chart_svg()
    for p in (ROOT / "docs" / "img" / "errors-by-field.svg", ROOT / "site" / "media" / "errors-by-field.svg"):
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(svg, encoding="utf-8")
    print("wrote results/summary.md, docs/img/errors-by-field.svg, site/media/errors-by-field.svg")
    return 0


if __name__ == "__main__":
    sys.exit(main())
